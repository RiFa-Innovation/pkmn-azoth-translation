"""The goal book: what the agent should achieve, in what order, how to tell it is done, and a journal of what happened.

    data/agent_goals.json     authored goals (committed). Fields per goal:
        id, title, chapter, requires [goal ids], done (condition), do [route tokens, see play_loop.py], checkpoint (name or null),
        status  "unverified" | "verified" | "blocked", verified (date), notes
    data/agent_journal.jsonl  one JSON event per line, appended by runs (committed: it is the history the doc is rendered from)
    docs/AGENT_GOALS.md       generated by `python3 scripts/agent/goalbook.py render`; do not edit by hand

Conditions (live, read from the running game, so any save can be loaded and the next undone goal is found):
    {"flag": "0x820"}  {"var": ["0x5105", ">=", 3]}  {"map": "43.5"}  {"party": 1}  {"badges": 2}  {"not": c}  {"all": [c..]}  {"any": [c..]}
Flags go through the game's own `checkflag` (verified 2026-10-24: works for the hack's flags >= 0x900 too, where the save-block bitmap does not).
Vars of the hack (>= 0x4000) are read from its var array; vanilla vars (< 0x4000) are not supported yet.
"""
import json
import os
import struct
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.dirname(HERE))

GOALS = os.path.join(ROOT, "data/agent_goals.json")
JOURNAL = os.path.join(ROOT, "data/agent_journal.jsonl")
DOC = os.path.join(ROOT, "docs/AGENT_GOALS.md")
CTX, SCRIPT = 0x03000EB0, 0x0203FF00
VAR_BASE_RAM, VAR_BASE_ID = 0x2039374, 0x4000
BADGE_FLAGS = range(0x820, 0x828)
OPS = {">=": lambda a, b: a >= b, "==": lambda a, b: a == b, "<": lambda a, b: a < b, "!=": lambda a, b: a != b}


def load(path=GOALS):
    return json.load(open(path))["goals"]


def flag_get(e, fid):
    """Ask the game: run `checkflag fid; end` and read the comparison result. Only call with no script running."""
    e.write(SCRIPT, bytes([0x2B]) + struct.pack("<H", fid) + bytes([0x02]))
    e.write(CTX + 8, struct.pack("<I", SCRIPT))
    e.write(CTX, b"\x00\x01")
    e.write(0x03000EA8, b"\x00")
    e.wait(4)
    return bool(e.read(CTX + 2, 1)[0])


def var_get(e, vid):
    if vid < VAR_BASE_ID:
        raise ValueError(f"vanilla var {vid:#x}: not supported yet")
    return struct.unpack("<H", e.read(VAR_BASE_RAM + 2 * (vid - VAR_BASE_ID), 2))[0]


def evaluate(e, cond, play=None):
    """True/False for a condition (see the module docstring)."""
    import play as pl
    (k, v), = cond.items()
    if k == "flag":
        return flag_get(e, int(v, 0))
    if k == "var":
        vid, op, val = v
        return OPS[op](var_get(e, int(vid, 0)), val)
    if k == "map":
        g, n = map(int, v.split("."))
        return pl.pos(e)[2:] == (g, n)
    if k == "party":
        return e.read(0x02024029, 1)[0] >= v
    if k == "badges":
        return sum(flag_get(e, f) for f in BADGE_FLAGS) >= v
    if k == "not":
        return not evaluate(e, v)
    if k == "all":
        return all(evaluate(e, c) for c in v)
    if k == "any":
        return any(evaluate(e, c) for c in v)
    raise ValueError(f"unknown condition {k!r}")


def next_goal(e, goals):
    """First goal that is not done and whose requirements are done; (goal, reason) or (None, why). Evaluated live."""
    by_id = {g["id"]: g for g in goals}
    done = {}

    def is_done(gid):
        if gid not in done:
            done[gid] = evaluate(e, by_id[gid]["done"])
        return done[gid]

    waiting = []
    for g in goals:
        if is_done(g["id"]):
            continue
        missing = [r for r in g.get("requires", []) if not is_done(r)]
        if not missing:
            return g, "ready"
        waiting.append((g["id"], missing))
    return None, ("all goals done" if not waiting else f"nothing ready; waiting on {waiting[:3]}")


def journal(kind, **kw):
    ev = {"t": time.strftime("%Y-%m-%dT%H:%M:%S"), "kind": kind, **kw}
    with open(JOURNAL, "a") as f:
        f.write(json.dumps(ev) + "\n")
    return ev


def set_status(goal_id, status, notes=None):
    data = json.load(open(GOALS))
    for g in data["goals"]:
        if g["id"] == goal_id:
            g["status"] = status
            if status == "verified":
                g["verified"] = time.strftime("%Y-%m-%d")
            if notes:
                g["notes"] = notes
    json.dump(data, open(GOALS, "w"), indent=1, ensure_ascii=False)
    open(GOALS, "a").write("\n")


def render():
    goals = load()
    events = [json.loads(l) for l in open(JOURNAL)] if os.path.exists(JOURNAL) else []
    last = {}
    for ev in events:
        if ev.get("goal"):
            last[ev["goal"]] = ev
    n_ver = sum(g["status"] == "verified" for g in goals)
    out = ["# Agent goals and journal", "",
           "> Generated by `python3 scripts/agent/goalbook.py render` from `data/agent_goals.json` and `data/agent_journal.jsonl`. "
           "Do not edit by hand. Playtest tooling for the Jev agent (`docs/JEV_AGENT_SPEC.md`); nothing here ships in the ROM.", "",
           f"**{len(goals)} goals, {n_ver} verified in the emulator, {sum(g['status'] == 'blocked' for g in goals)} blocked.** "
           "A goal is *done* when its condition holds in the live game, so any save can be loaded and the agent picks up at the first "
           "goal that is not done and whose requirements are.", "",
           "| # | Goal | Chapter | Requires | Done when | Status | Last event |", "|---|---|---|---|---|---|---|"]
    for i, g in enumerate(goals, 1):
        ev = last.get(g["id"])
        le = f"{ev['kind']} {ev['t'][:10]}" if ev else ""
        out.append(f"| {i} | **{g['title']}** (`{g['id']}`) | {g.get('chapter', '')} | {', '.join(g.get('requires', [])) or '-'} | "
                   f"`{json.dumps(g['done'])}` | {g['status']}{' ' + g['verified'] if g.get('verified') else ''} | {le} |")
    out += ["", "## Goal notes", ""]
    for g in goals:
        out.append(f"- **{g['title']}** (`{g['id']}`): " + (g.get("notes") or "no notes") +
                   (f" Checkpoint: `{g['checkpoint']}`." if g.get("checkpoint") else ""))
    out += ["", "## Journal (latest 40 events)", "", "| Time | Event | Goal | Detail |", "|---|---|---|---|"]
    for ev in events[-40:][::-1]:
        detail = ev.get("detail") or ev.get("reason") or ""
        out.append(f"| {ev['t']} | {ev['kind']} | {ev.get('goal', '')} | {str(detail)[:140].replace('|', '/')} |")
    open(DOC, "w").write("\n".join(out) + "\n")
    return DOC


if __name__ == "__main__":
    if sys.argv[1:2] == ["render"]:
        print(render())
    else:
        print(__doc__)
