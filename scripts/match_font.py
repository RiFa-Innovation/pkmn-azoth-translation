"""Match the hack's CJK font glyphs against a reference GB2312 bitmap font.

Renders each glyph (half-row compressed format) from the font at `base`, matches
against reference glyphs rendered with a system CJK font, and emits the full
charmap (2-byte code -> character). Font-matching completes the charmap with no
human Chinese reader.

Usage:
    python3 scripts/match_font.py <base> [max_code] [stride]
"""
import sys
import json
import numpy as np
from PIL import Image, ImageDraw, ImageFont

# --- half-row decompression tables (vanilla FR) ---
OFFSETS = bytes([0x00,0x01,0x02,0x00,0x03,0x04,0x05,0x03,0x06,0x07,0x08,0x06,0x00,0x01,0x02,0x00,
0x09,0x0A,0x0B,0x09,0x0C,0x0D,0x0E,0x0C,0x0F,0x10,0x11,0x0F,0x09,0x0A,0x0B,0x09,
0x12,0x13,0x14,0x12,0x15,0x16,0x17,0x15,0x18,0x19,0x1A,0x18,0x12,0x13,0x14,0x12,
0x00,0x01,0x02,0x00,0x03,0x04,0x05,0x03,0x06,0x07,0x08,0x06,0x00,0x01,0x02,0x00,
0x1B,0x1C,0x1D,0x1B,0x1E,0x1F,0x20,0x1E,0x21,0x22,0x23,0x21,0x1B,0x1C,0x1D,0x1B,
0x24,0x25,0x26,0x24,0x27,0x28,0x29,0x27,0x2A,0x2B,0x2C,0x2A,0x24,0x25,0x26,0x24,
0x2D,0x2E,0x2F,0x2D,0x30,0x31,0x32,0x30,0x33,0x34,0x35,0x33,0x2D,0x2E,0x2F,0x2D,
0x1B,0x1C,0x1D,0x1B,0x1E,0x1F,0x20,0x1E,0x21,0x22,0x23,0x21,0x1B,0x1C,0x1D,0x1B,
0x36,0x37,0x38,0x36,0x39,0x3A,0x3B,0x39,0x3C,0x3D,0x3E,0x3C,0x36,0x37,0x38,0x36,
0x3F,0x40,0x41,0x3F,0x42,0x43,0x44,0x42,0x45,0x46,0x47,0x45,0x3F,0x40,0x41,0x3F,
0x48,0x49,0x4A,0x48,0x4B,0x4C,0x4D,0x4B,0x4E,0x4F,0x50,0x4E,0x48,0x49,0x4A,0x48,
0x36,0x37,0x38,0x36,0x39,0x3A,0x3B,0x39,0x3C,0x3D,0x3E,0x3C,0x36,0x37,0x38,0x36,
0x00,0x01,0x02,0x00,0x03,0x04,0x05,0x03,0x06,0x07,0x08,0x06,0x00,0x01,0x02,0x00,
0x09,0x0A,0x0B,0x09,0x0C,0x0D,0x0E,0x0C,0x0F,0x10,0x11,0x0F,0x09,0x0A,0x0B,0x09,
0x12,0x13,0x14,0x12,0x15,0x16,0x17,0x15,0x18,0x19,0x1A,0x18,0x12,0x13,0x14,0x12,
0x00,0x01,0x02,0x00,0x03,0x04,0x05,0x03,0x06,0x07,0x08,0x06,0x00,0x01,0x02,0x00])
LOOKUP = [0]*81
for l in range(3):
    for k in range(3):
        for j in range(3):
            for i in range(3):
                LOOKUP[i+3*j+9*k+27*l] = (l<<12)|(k<<8)|(j<<4)|i


def render_hack_glyph(data, off, stride=64):
    idxs = data[off:off+stride]
    fg = bytearray(256)
    for pos in range(stride):
        v = LOOKUP[OFFSETS[idxs[pos]]]
        p = (v & 0xF, (v>>4)&0xF, (v>>8)&0xF, (v>>12)&0xF)
        tile = pos // 16; w = pos % 16
        row = w // 2; half = w % 2
        x0 = (tile % 2)*8 + half*4; y0 = (tile // 2)*8 + row
        for q in range(4):
            if p[q] == 1:
                fg[y0*16 + x0+q] = 1
    return np.frombuffer(bytes(fg), dtype=np.uint8)


def render_ref(ch, font, size=16, thr=90):
    img = Image.new('L', (16, 16), 0)
    d = ImageDraw.Draw(img)
    bbox = d.textbbox((0, 0), ch, font=font)
    w = bbox[2]-bbox[0]; h = bbox[3]-bbox[1]
    d.text(((16-w)/2 - bbox[0], (16-h)/2 - bbox[1]), ch, font=font, fill=255)
    a = np.array(img)
    return (a > thr).astype(np.uint8).ravel()


def gb2312_chars():
    """All GB2312 hanzi + symbols, in the standard order."""
    chars = []
    for lead in range(0xB0, 0xF8):      # level 1 + 2 hanzi
        for trail in range(0xA1, 0xFF):
            try:
                chars.append(bytes([lead, trail]).decode('gb2312'))
            except Exception:
                chars.append(None)
    for lead in range(0xA1, 0xAA):      # symbols
        for trail in range(0xA1, 0xFF):
            try:
                chars.append(bytes([lead, trail]).decode('gb2312'))
            except Exception:
                chars.append(None)
    return chars


def main():
    base = int(sys.argv[1], 16)
    max_code = int(sys.argv[2], 16) if len(sys.argv) > 2 else 0x1400
    stride = int(sys.argv[3]) if len(sys.argv) > 3 else 64
    rom = open("roms/Pokemon Mercury 1.3.3 (patched).gba", "rb").read()
    font = ImageFont.truetype("/System/Library/Fonts/Hiragino Sans GB.ttc", 16)

    ref_chars = gb2312_chars()
    refs = []
    valid_idx = []
    for i, ch in enumerate(ref_chars):
        if ch:
            refs.append(render_ref(ch, font))
            valid_idx.append(i)
    refs = np.stack(refs)

    charmap = {}
    for code in range(max_code):
        g = render_hack_glyph(rom, base + code*stride, stride)
        if g.sum() == 0:
            continue
        # Jaccard similarity against all references
        inter = (refs & g).sum(axis=1)
        union = (refs | g).sum(axis=1)
        union[union == 0] = 1
        sim = inter / union
        best = int(np.argmax(sim))
        if sim[best] > 0.35:
            charmap[code] = ref_chars[valid_idx[best]]

    json.dump({f"{k:04X}": v for k, v in sorted(charmap.items())},
              open("scripts/charmap_matched.json", "w", encoding="utf-8"),
              ensure_ascii=False, indent=1)
    print(f"matched {len(charmap)} codes -> scripts/charmap_matched.json")


if __name__ == "__main__":
    main()
